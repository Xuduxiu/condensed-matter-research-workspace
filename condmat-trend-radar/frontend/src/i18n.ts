export function statusLabel(status: string | null | undefined, t: Translation) {
  if (!status) return t.unknown;
  const labels: Record<string, string> = {
    emerging: t.emerging,
    active: t.active,
    cooling: t.cooling,
    stale: t.stale,
    persistent: t.persistent,
  };
  return labels[status] ?? status;
}


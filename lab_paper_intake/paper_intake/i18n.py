def t(key: str, lang: str = "zh", **kwargs: object) -> str:
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS["zh"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def status_label(status: str, lang: str = "zh") -> str:
    return t(f"pdf_status_{status}", lang)
